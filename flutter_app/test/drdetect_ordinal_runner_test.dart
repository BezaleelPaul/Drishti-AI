import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:image/image.dart' as img;
import 'package:netra_ai_mobile/services/ml/drdetect_ordinal_runner.dart';
import 'package:netra_ai_mobile/services/ml/model_runner.dart';
import 'package:netra_ai_mobile/services/ml/pipeline_schema.dart';

/// Fail-closed + parity contracts for the DRDetect ordinal TFLite runner.
///
/// The interpreter itself cannot run under `flutter test` (no platform
/// channels), so these tests cover everything that CAN be verified in pure
/// Dart: cut-point decoding parity with classifier.py, the golden
/// preprocessing tensors generated by the exact Python production pipeline,
/// and the FallbackModelRunner failover behavior.
void main() {
  group('DrDetectOrdinalTfliteRunner fail-closed contract', () {
    test('predict before initialize throws StateError', () async {
      final runner = DrDetectOrdinalTfliteRunner();
      final image = img.Image(width: 64, height: 64);
      await expectLater(runner.predict(image), throwsStateError);
    });

    test('reports honest model identity', () {
      final runner = DrDetectOrdinalTfliteRunner();
      expect(runner.modelId, 'drdetect_ordinal_tflite');
      expect(runner.modelVersion, 'v1.0.0-ordinal-512px-fp32');
      expect(
        DrDetectOrdinalTfliteRunner.shippedModelAsset,
        contains('drdetect_ordinal_512_fp32.tflite'),
      );
    });

    test('dispose is safe to call before initialize', () {
      final runner = DrDetectOrdinalTfliteRunner();
      expect(runner.dispose, returnsNormally);
    });

    test('degenerate (tiny) image throws ArgumentError, not a grade', () {
      final image = img.Image(width: 4, height: 4);
      expect(
        () => DrDetectOrdinalTfliteRunner.preprocessToNhwcForTest(image),
        throwsArgumentError,
      );
    });

    test('fully-black image throws (no retinal region), not a grade', () {
      final image = img.Image(width: 64, height: 64);
      // All pixels already default to 0 (black) with alpha 0.
      expect(
        () => DrDetectOrdinalTfliteRunner.preprocessToNhwcForTest(image),
        throwsArgumentError,
      );
    });
  });

  group(
    'cut-point decoding parity (classifier.py::_predict_onnx_drdetect)',
    () {
      final runner = DrDetectOrdinalTfliteRunner();

      DrModelOutput decode(double score) => runner.decodeScoreForTest(score);

      test('grade boundaries use strict > threshold, matching Python', () {
        expect(decode(0.0).grade, DrGrade.noDr);
        expect(decode(0.5).grade, DrGrade.noDr); // 0.5 > 0.5 is False
        expect(decode(0.5001).grade, DrGrade.mildNpdr);
        expect(decode(1.5).grade, DrGrade.mildNpdr);
        expect(decode(1.5001).grade, DrGrade.moderateNpdr);
        expect(decode(2.5).grade, DrGrade.moderateNpdr);
        expect(decode(2.5001).grade, DrGrade.severeNpdr);
        expect(decode(3.5).grade, DrGrade.severeNpdr);
        expect(decode(3.5001).grade, DrGrade.proliferativeDr);
        expect(decode(4.0).grade, DrGrade.proliferativeDr);
      });

      test('out-of-range scores clamp to [0, 4] grade, no crash', () {
        expect(decode(-1.0).grade, DrGrade.noDr);
        expect(decode(99.0).grade, DrGrade.proliferativeDr);
      });

      test('probabilities are a normalized 5-class kernel distribution', () {
        final out = decode(1.621);
        final probs = out.probabilities!;
        expect(probs.length, 5);
        final sum = probs.fold<double>(0, (a, b) => a + b);
        expect(sum, closeTo(1.0, 1e-9));
        // Kernel sigma=0.65 around 1.621 -> mass concentrated on classes 1..2.
        expect(probs[1] + probs[2], greaterThan(0.9));
        // Class 0 sits 1.621 (~2.5 sigma) from the score -> ~2.7% tail mass,
        // which is expected Gaussian-kernel behaviour, not a red flag.
        expect(probs[0], lessThan(0.05));
        expect(probs[4], lessThan(0.01));
      });

      test('referable flag is score >= 1.5 (threshold[1]), like Python', () {
        expect(decode(1.4999).referable, isFalse);
        expect(decode(1.5).referable, isTrue);
        expect(decode(2.0).referable, isTrue);
      });

      test('referableScore carries the raw model score unchanged', () {
        expect(decode(1.621).referableScore, 1.621);
        expect(decode(0.0).referableScore, 0.0);
      });

      test('uncertainty uses 1-top1 convention (orchestrator-compatible)', () {
        // A score near an integer, far from any cut-point (>=0.5 away), gives
        // a genuinely sharp kernel. 3.0 is 0.5 from cut-point 3.5 -> top-1
        // ~0.61 (sigma=0.65 is broad), so uncertainty lands near 0.39.
        final sharp = decode(3.0);
        expect(sharp.uncertainty!, lessThan(0.45));
        // Far tail, e.g. score 4.0, is sharper still.
        expect(decode(4.0).uncertainty!, lessThan(sharp.uncertainty!));
        // Midway between two cut-points (2.0 is equidistant from 1.5 and 2.5)
        // the kernel splits mass evenly, giving the lowest top-1 (~0.6135)
        // and thus the highest uncertainty, which peaks just below 0.39. This
        // is well under the orchestrator's 0.4 gate, confirming the 1-top1
        // convention never false-trips the low-confidence path (the old
        // exp(-dist) convention always landed above 0.6).
        final ambiguous = decode(2.0);
        expect(ambiguous.uncertainty!, greaterThan(0.38));
        expect(ambiguous.uncertainty!, lessThan(0.4));
        // The old exp(-dist) convention was ALWAYS > 0.6 for 1.0-spaced cuts,
        // which would have flagged every ordinal result as low-confidence.
        expect(decode(0.0).uncertainty!, lessThan(0.4));
      });

      test('top2Margin = top1 - top2, positive and < 1', () {
        final out = decode(1.621);
        final margin = out.top2Margin!;
        expect(margin, greaterThan(0));
        expect(margin, lessThan(1.0));
        // Margin is top1 - top2 over the sorted distribution, not a fixed
        // class pair (which pair wins depends on where the score lands).
        final sorted = [...out.probabilities!]..sort((a, b) => b.compareTo(a));
        expect(margin, closeTo(sorted[0] - sorted[1], 1e-12));
      });

      test('reports real backend identity on the output', () {
        final out = decode(1.0);
        expect(out.modelId, 'drdetect_ordinal_tflite');
        expect(out.modelVersion, 'v1.0.0-ordinal-512px-fp32');
      });
    },
  );

  group('golden preprocessing parity (exact Python production pipeline)', () {
    // Goldens generated by scripts/convert/generate_drdetect_dart_goldens.py
    // from the EXACT classifier.py pipeline (native-res Ben Graham sigma=20,
    // cv2 box-approximation blur). The Dart port uses the package
    // gaussianBlur (same box-approximation family) with the measured
    // working-size fast path (results/drdetect_fastpreprocess_tolerance.json:
    // max score drift 0.059, 10/10 grade agreement). Tolerances absorb only
    // residual blur-kernel / resize differences while still catching wrong
    // normalization, channel order, or crop geometry.
    const meanTolerance = 0.05;
    const sampleTolerance = 0.25;

    final fixturesFile = File('test/fixtures/drdetect_preprocess_goldens.json');
    late Map<String, dynamic> goldensDoc;
    late List<dynamic> goldens;

    setUpAll(() {
      goldensDoc =
          jsonDecode(fixturesFile.readAsStringSync()) as Map<String, dynamic>;
      goldens = goldensDoc['goldens'] as List<dynamic>;
    });

    test('golden file is present and covers >= 3 clinical fixtures', () {
      expect(goldens.length, greaterThanOrEqualTo(3));
    });

    for (var g = 0; g < 3; g++) {
      test('fixture #$g preprocessing stats match Python golden', () {
        final golden = goldens[g] as Map<String, dynamic>;
        final relPath = golden['image'] as String;
        final file = File('../$relPath');
        expect(file.existsSync(), isTrue, reason: 'missing fixture $relPath');

        final decoded = img.decodeJpg(file.readAsBytesSync());
        expect(decoded, isNotNull);

        final nhwc = DrDetectOrdinalTfliteRunner.preprocessToNhwcForTest(
          decoded!,
        );
        expect(nhwc.length, 512 * 512 * 3);

        // Per-channel mean.
        final goldenMean = (golden['mean'] as List).cast<double>();
        final mean = List<double>.filled(3, 0.0);
        for (var i = 0; i < 512 * 512; i++) {
          mean[0] += nhwc[i * 3];
          mean[1] += nhwc[i * 3 + 1];
          mean[2] += nhwc[i * 3 + 2];
        }
        for (var c = 0; c < 3; c++) {
          mean[c] /= 512 * 512;
          expect(
            mean[c],
            closeTo(goldenMean[c], meanTolerance),
            reason:
                'channel $c mean drifted (Dart=${mean[c]}, '
                'Python=${goldenMean[c]})',
          );
        }

        final samples = golden['samples'] as List<dynamic>;
        var maxDiff = 0.0;
        var maxAt = '';
        for (final s in samples) {
          final sm = s as Map<String, dynamic>;
          final y = sm['y'] as int;
          final x = sm['x'] as int;
          final c = sm['c'] as int;
          final expected = (sm['v'] as num).toDouble();
          final actual = nhwc[(y * 512 + x) * 3 + c];
          final d = (actual - expected).abs();
          if (d > maxDiff) {
            maxDiff = d;
            maxAt = '($y,$x,$c) exp=$expected act=$actual';
          }
        }
        expect(maxDiff, lessThan(sampleTolerance), reason: 'worst at $maxAt');

        // Decode parity: the Dart decode of the ONNX score must reproduce
        // the Python-decoded grade exactly.
        final onnxScore = (golden['onnx_score'] as num).toDouble();
        final onnxGrade = golden['onnx_grade'] as int;
        final runner = DrDetectOrdinalTfliteRunner();
        final decoded2 = runner.decodeScoreForTest(onnxScore);
        expect(
          decoded2.grade.value,
          onnxGrade,
          reason:
              'decode($onnxScore) -> ${decoded2.grade.value}, '
              'expected $onnxGrade',
        );
      });
    }
  });

  group('FallbackModelRunner failover chain', () {
    DrModelRunner runnerThatFailsToInit(String id) =>
        _FakeRunner(id, initError: StateError('$id unavailable'));

    test('initialize succeeds when the SECOND runner is usable', () async {
      final chain = FallbackModelRunner([
        runnerThatFailsToInit('primary'),
        _FakeRunner('secondary'),
      ]);
      await chain.initialize();
      expect(chain.active, isNotNull);
      expect(chain.modelId, 'secondary');
      chain.dispose();
    });

    test('initialize throws when every runner fails (fail closed)', () async {
      final chain = FallbackModelRunner([
        runnerThatFailsToInit('a'),
        runnerThatFailsToInit('b'),
      ]);
      await expectLater(chain.initialize(), throwsStateError);
      expect(chain.modelId, 'unavailable');
      chain.dispose();
    });

    test('predict before initialize throws StateError', () async {
      final chain = FallbackModelRunner([_FakeRunner('only')]);
      final image = img.Image(width: 8, height: 8);
      await expectLater(chain.predict(image), throwsStateError);
    });

    test('predict falls through to next runner when the active one throws '
        'at runtime', () async {
      final primary = _FakeRunner('primary', predictError: StateError('crash'));
      final chain = FallbackModelRunner([primary, _FakeRunner('backup')]);
      await chain.initialize();
      expect(chain.modelId, 'primary');

      final out = await chain.predict(img.Image(width: 8, height: 8));
      expect(out.modelId, 'backup');
      expect(chain.active!.modelId, 'backup');
      chain.dispose();
    });

    test('predict rethrows when ALL runners fail at runtime', () async {
      final chain = FallbackModelRunner([
        _FakeRunner('a', predictError: StateError('crash a')),
        _FakeRunner('b', predictError: StateError('crash b')),
      ]);
      await chain.initialize();
      await expectLater(
        chain.predict(img.Image(width: 8, height: 8)),
        throwsStateError,
      );
      chain.dispose();
    });

    test('dispose is safe on an uninitialized chain', () {
      final chain = FallbackModelRunner([_FakeRunner('x')]);
      expect(chain.dispose, returnsNormally);
    });
  });
}

class _FakeRunner implements DrModelRunner {
  _FakeRunner(this._id, {this.initError, this.predictError});

  final String _id;
  final Object? initError;
  final Object? predictError;
  bool _initialized = false;

  @override
  String get modelId => _id;

  @override
  String get modelVersion => 'fake-1';

  @override
  Future<void> initialize() async {
    final err = initError;
    if (err != null) throw err;
    _initialized = true;
  }

  @override
  Future<DrModelOutput> predict(img.Image image) async {
    final err = predictError;
    if (err != null) throw err;
    if (!_initialized) throw StateError('$_id not initialized');
    return DrModelOutput(
      grade: DrGrade.noDr,
      probabilities: const [1, 0, 0, 0, 0].map((e) => e.toDouble()).toList(),
      referableScore: 0.0,
      referable: false,
      uncertainty: 0.0,
      modelId: _id,
      modelVersion: 'fake-1',
      top2Margin: 1.0,
    );
  }

  @override
  void dispose() {}
}
